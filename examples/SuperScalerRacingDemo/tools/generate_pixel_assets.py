#!/usr/bin/env python3
"""Generate the original 8x8 pixel tiles and their zero-allocation RGB565 header."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "pixel_art"
SRC = ROOT / "src" / "pixel_art_tiles.h"

PALETTE = {
    ".": None,
    "d": 0x4A49,  # asphalt shadow
    "l": 0x8C51,  # asphalt glint
    "r": 0x9B66,  # sandstone pebble
    "h": 0xC42A,  # sunlit sandstone
    "s": 0x8B04,  # dry shadow
}
TILES = {
    "ROAD": {
        "base": 0x7BCF,
        "rows": ["........", "..d.....", "........", "....l...",
                 "........", "d.......", ".....l..", ".......d"],
    },
    "SAND": {
        "base": 0xB425,
        "rows": ["......r.", "........", "..r.....", ".......h",
                 "........", ".....r..", "r.......", "...h...."],
    },
}

def rgb565_to_rgb(c: int) -> tuple[int, int, int]:
    r, g, b = (c >> 11) & 31, (c >> 5) & 63, c & 31
    return (r * 255 // 31, g * 255 // 63, b * 255 // 31)

def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    lines = ["/* Generated by tools/generate_pixel_assets.py; do not hand edit. */", "#pragma once", "#include <stdint.h>"]
    for name, tile in TILES.items():
        rows = tile["rows"]
        assert len(rows) == 8 and all(len(row) == 8 for row in rows)
        values = [PALETTE[ch] or 0 for row in rows for ch in row]
        lines.append(f"static const uint16_t VXPE_{name}_TILE_RGB565[64]={{")
        for i in range(0, 64, 8):
            lines.append("  " + ",".join(f"0x{v:04X}" for v in values[i:i+8]) + ",")
        lines.append("};")
        image = Image.new("RGB", (8, 8), rgb565_to_rgb(tile["base"]))
        px = image.load()
        for y, row in enumerate(rows):
            for x, ch in enumerate(row):
                if PALETTE[ch] is not None:
                    px[x, y] = rgb565_to_rgb(PALETTE[ch])
        image.save(OUT / f"{name.lower()}_tile.png", optimize=False)
    SRC.write_text("\n".join(lines) + "\n", encoding="utf-8")

if __name__ == "__main__":
    main()
